const standaloneGenericBrandTokenSet = new Set<string>(
  standaloneGenericBrandTokens,
);

export function isStandaloneGenericBrand(value: string | null): boolean {
  if (!value) return false;

  const normalizedValue = value
    .trim()
    .toLocaleLowerCase("it-IT")
    .replace(/[’']/g, "");

  return standaloneGenericBrandTokenSet.has(normalizedValue);
}

